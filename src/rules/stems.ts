export const STEMS: Record<StemGroup, Entry[]> = { temp: TEMP, light: LIGHT, sound: SOUND };

export interface StemHit {
  group: StemGroup;
  /** Слово из записи, как написано (в нижнем регистре). */
  word: string;
  polarity: number;
}

function matchEntry(token: string, entries: Entry[]): Entry | null {
  for (const e of entries) {
    const stem = e[0];
    if (stem.startsWith('=') ? token === stem.slice(1) : token.startsWith(stem)) return e;
  }
  return null;
}

/** Все слова текста, попавшие в словарь, в порядке записи. */
export function findStems(text: string): StemHit[] {
  const surface = rawWords(text).map((w) => w.toLowerCase());
  const hits: StemHit[] = [];
  lowerWords(text).forEach((token, i) => {
    for (const group of ['temp', 'light', 'sound'] as const) {
      const e = matchEntry(token, STEMS[group]);
      if (e) {
        hits.push({ group, word: surface[i], polarity: e[1] });
        break;
      }
    }
  });
  return hits;
}

export function groupHits(hits: StemHit[], group: StemGroup): StemHit[] {
  return hits.filter((h) => h.group === group);
}

/** Сумма полярностей группы. */
export function score(hits: StemHit[], group: StemGroup): number {
  return sum(groupHits(hits, group).map((h) => h.polarity));
}

export function wordsOf(hits: StemHit[], pred: (h: StemHit) => boolean = () => true): string[] {
  return hits.filter(pred).map((h) => h.word);
}
